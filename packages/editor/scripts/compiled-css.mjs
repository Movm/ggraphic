/**
 * The editor's stylesheet for hosts without Tailwind (`@ggraphic/editor/styles/compiled`).
 *
 * Tailwind v4 compiles exactly the classes `src/` uses, with the theme mapping, utilities and
 * variant of `src/styles/tailwind.css`, and the editor rules of `editor.css`. Then:
 *
 * - Every rule sits in `@layer ggraphic`, so any unlayered host rule wins without `!important`.
 * - Every selector is scoped: its subject must be `[data-ggraphic]` or inside one. The classes
 *   stay as they are (no prefix); the scope adds no specificity (`:where`). The editor root and
 *   every portal the editor opens on `<body>` carry the attribute (`EDITOR_SCOPE`).
 * - Preflight comes along, scoped the same way, so the host page keeps its own reset.
 * - Tailwind's theme variables land on the scope roots, not on `:root`, so they never meet a
 *   host's own `--color-*` / `--spacing`.
 * - The token defaults (`tokens.css`) stay global in `:where(:root)`: they are the theming API,
 *   a host overrides them on `:root` or `[data-theme]` as before. So do the `html:has(...)` rules
 *   of `editor.css`, which only apply while an editor is on the page.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';

import { compile, optimize } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';
import { transform } from 'lightningcss';

export const SCOPE_ATTRIBUTE = 'data-ggraphic';

const attr = { type: 'attribute', namespace: null, name: SCOPE_ATTRIBUTE, operation: null };
/** `:where([data-ggraphic], [data-ggraphic] *)`: the scope root or anything inside it. */
const IN_SCOPE = {
  type: 'pseudo-class',
  kind: 'where',
  selectors: [[attr], [attr, { type: 'combinator', value: 'descendant' }, { type: 'universal' }]],
};
/** `:where([data-ggraphic])`: where Tailwind's `:root, :host, html` rules go. */
const SCOPE_ROOT = [{ type: 'pseudo-class', kind: 'where', selectors: [[attr]] }];

const isDocumentRoot = (c) =>
  (c.type === 'pseudo-class' && (c.kind === 'root' || c.kind === 'host')) ||
  (c.type === 'type' && c.name === 'html');

/** `html:has(.canvas-editor-layout) …`: page-level rules that already apply only with an editor. */
const isEditorPageRule = ([first, second]) =>
  first?.type === 'type' && first.name === 'html' && second?.kind === 'has';

/** One selector, its subject compound restricted to the scope. */
function scopeSelector(selector) {
  if (isEditorPageRule(selector)) return selector;
  if (selector.length === 1 && isDocumentRoot(selector[0])) return SCOPE_ROOT;
  const lastCombinator = selector.findLastIndex((c) => c.type === 'combinator');
  const pseudoElement = selector.findIndex(
    (c, i) => i > lastCombinator && c.type === 'pseudo-element'
  );
  const at = pseudoElement === -1 ? selector.length : pseudoElement;
  return [...selector.slice(0, at), IN_SCOPE, ...selector.slice(at)];
}

/** Scoped, layered, minified CSS for the editor in `srcDir`. */
export async function compileEditorCss(srcDir) {
  const styles = path.join(srcDir, 'styles');
  // Only the parts of `tailwindcss` that rules and utilities need; `tailwind.css` brings the
  // theme mapping, `@source` of `src/`, the extra utilities and the `kbd` variant.
  const entry = `
    @layer theme, base, components, utilities;
    @import 'tailwindcss/theme.css' layer(theme);
    @import 'tailwindcss/preflight.css' layer(base);
    @import 'tailwindcss/utilities.css' layer(utilities);
    @import './editor.css';
    @import './tailwind.css';
  `;
  const compiler = await compile(entry, { base: styles, onDependency: () => {} });
  const scanner = new Scanner({
    sources: compiler.sources.map((s) => ({ ...s, base: s.base })),
  });
  const built = compiler.build(scanner.scan());
  const flat = optimize(built, { minify: false }).code;

  const scoped = transform({
    filename: 'compiled.css',
    code: Buffer.from(`@layer ggraphic{${flat}}`),
    minify: true,
    // The visitor sees each top-level selector of a rule, not the ones inside `:is()` & co.
    visitor: { Selector: scopeSelector },
  }).code.toString();

  const tokens = transform({
    filename: 'tokens.css',
    code: Buffer.from(`@layer ggraphic.tokens{${readFileSync(path.join(styles, 'tokens.css'))}}`),
    minify: true,
  }).code.toString();

  return `/*! @ggraphic/editor, compiled styles | AGPL-3.0-only | contains CSS generated by Tailwind CSS (MIT, Copyright (c) Tailwind Labs, Inc.), see THIRD_PARTY_NOTICES */\n@layer ggraphic.tokens;${tokens}${scoped}\n`;
}
