import { isIP } from 'node:net';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const optionalString = z
  .string()
  .trim()
  .transform((value) => (value === '' ? null : value))
  .nullable()
  .default(null);

const flag = (fallback: boolean) =>
  z
    .enum(['true', 'false'])
    .default(fallback ? 'true' : 'false')
    .transform((v) => v === 'true');

/** Unset keeps the default (follow the keys), `false` switches a configured tool off. */
const toggle = z
  .enum(['true', 'false'])
  .optional()
  .transform((v) => (v === undefined ? null : v === 'true'));

const PROXY_KEYWORDS = new Set(['loopback', 'linklocal', 'uniquelocal']);

function isProxyEntry(entry: string): boolean {
  if (PROXY_KEYWORDS.has(entry)) return true;
  const [address, bits, ...rest] = entry.split('/');
  if (rest.length > 0 || !address) return false;
  const family = isIP(address);
  if (family === 0) return false;
  if (bits === undefined) return true;
  if (!/^\d{1,3}$/.test(bits)) return false;
  return Number(bits) <= (family === 4 ? 32 : 128);
}

/**
 * Express `trust proxy`: false, a hop count, or a comma-separated list of proxy addresses,
 * subnets and the keywords loopback/linklocal/uniquelocal. `true` is refused: it trusts
 * every hop, so any client could choose its own address by sending X-Forwarded-For.
 */
const trustProxy = z
  .string()
  .default('false')
  .transform((v, ctx): false | number | string[] => {
    if (v === 'false') return false;
    if (/^\d{1,2}$/.test(v)) return Number(v);
    const entries = v.split(',').map((e) => e.trim());
    if (entries.length > 0 && entries.every(isProxyEntry)) return entries;
    ctx.addIssue({
      code: 'custom',
      message: 'a hop count or a list of proxy addresses/subnets; true is not accepted',
    });
    return z.NEVER;
  });

const envSchema = z.object({
  DATABASE_URL: z.string().min(1),
  HOST: z.string().default('127.0.0.1'),
  PORT: z.coerce.number().int().min(1).max(65535).default(8080),
  // Both paths resolve relative to apps/studio-server, from src/ (dev, tests) and dist/ (build) alike.
  DATA_DIR: z.string().default(fileURLToPath(new URL('../data', import.meta.url))),
  STATIC_DIR: z.string().default(fileURLToPath(new URL('../../studio/dist', import.meta.url))),
  UPLOAD_MAX_BYTES: z.coerce
    .number()
    .int()
    .positive()
    .default(10 * 1024 * 1024),
  THUMBNAIL_MAX_BYTES: z.coerce
    .number()
    .int()
    .positive()
    .default(2 * 1024 * 1024),
  DOCUMENT_MAX_BYTES: z.coerce
    .number()
    .int()
    .positive()
    .default(5 * 1024 * 1024),
  FONT_MAX_BYTES: z.coerce
    .number()
    .int()
    .positive()
    .default(5 * 1024 * 1024),
  COOKIE_SECURE: flag(true),
  ALLOW_REGISTRATION: flag(false),
  // Exactly "1": the operator knowingly serves sessions over plain HTTP beyond loopback.
  ALLOW_INSECURE_COOKIE: z.literal('1').optional(),
  TRUST_PROXY: trustProxy,
  // Required by the first-run setup. Without it the server generates one at start.
  SETUP_TOKEN: z.string().trim().min(16).max(200).optional(),
  OPENAI_BASE_URL: optionalString,
  OPENAI_API_KEY: optionalString,
  OPENAI_MODEL: optionalString,
  AI_TIMEOUT_MS: z.coerce.number().int().positive().default(60_000),
  AI_ENABLED: toggle,
  REMBG_URL: optionalString,
  REMBG_ENABLED: toggle,
  REMBG_TIMEOUT_MS: z.coerce.number().int().positive().default(60_000),
});

export interface AiConfig {
  baseUrl: string;
  apiKey: string;
  model: string;
  timeoutMs: number;
}

export interface RembgConfig {
  /** Operator-set base URL of the rembg server, without a trailing slash. */
  url: string;
  timeoutMs: number;
}

/** Tools that need an external service. Each is null when switched off. */
export interface Features {
  removeBackground: RembgConfig | null;
}

export interface Config {
  databaseUrl: string;
  host: string;
  port: number;
  uploadDir: string;
  staticDir: string;
  uploadMaxBytes: number;
  thumbnailMaxBytes: number;
  documentMaxBytes: number;
  fontMaxBytes: number;
  /** Data directory: uploads and brand assets live below it. */
  dataDir: string;
  /** false only for plain-HTTP setups whose browser drops Secure cookies (Safari on localhost). */
  cookieSecure: boolean;
  /** Self-registration after the first account. Off by default; invitations always work. */
  allowRegistration: boolean;
  /** COOKIE_SECURE=false on a non-loopback HOST, acknowledged with ALLOW_INSECURE_COOKIE=1. */
  allowInsecureCookie: boolean;
  trustProxy: false | number | string[];
  /**
   * The token the first-run setup must present; null once accounts exist. `SETUP_TOKEN`
   * or, on an empty instance, generated by server.ts at start.
   */
  setupToken: string | null;
  /** null when AI is not configured; the feature is then switched off. */
  ai: AiConfig | null;
  /** The other external tools; `ai` stays above because the AI routes read it directly. */
  features: Features;
}

/**
 * The rule for every external tool: on when its key or URL is present, off with
 * `<TOOL>_ENABLED=false`, and `<TOOL>_ENABLED=true` without the key or URL is an error.
 */
function resolveFeature<T>(
  name: string,
  enabled: boolean | null,
  needs: string,
  config: T | null
): T | null {
  if (enabled === false) return null;
  if (enabled === true && config === null) {
    throw new Error(`Invalid configuration: ${name}_ENABLED=true needs ${needs}`);
  }
  return config;
}

export function loadConfig(env: NodeJS.ProcessEnv = process.env): Config {
  // Empty values count as unset, so `FOO=` in .env or compose falls back to the default.
  const set = Object.fromEntries(
    Object.entries(env).filter(([, v]) => v !== undefined && v !== '')
  );
  const parsed = envSchema.safeParse(set);
  if (!parsed.success) {
    const fields = parsed.error.issues.map((issue) => issue.path.join('.')).join(', ');
    throw new Error(`Invalid configuration: ${fields}`);
  }
  const e = parsed.data;
  const loopback = e.HOST === 'localhost' || e.HOST === '::1' || /^127\./.test(e.HOST);
  if (!e.COOKIE_SECURE && !loopback && !e.ALLOW_INSECURE_COOKIE) {
    throw new Error(
      'Invalid configuration: COOKIE_SECURE=false sends session cookies over plain HTTP; on a non-loopback HOST it needs ALLOW_INSECURE_COOKIE=1'
    );
  }
  const ai = resolveFeature(
    'AI',
    e.AI_ENABLED,
    'OPENAI_BASE_URL, OPENAI_API_KEY and OPENAI_MODEL',
    e.OPENAI_BASE_URL && e.OPENAI_API_KEY && e.OPENAI_MODEL
      ? {
          baseUrl: e.OPENAI_BASE_URL.replace(/\/+$/, ''),
          apiKey: e.OPENAI_API_KEY,
          model: e.OPENAI_MODEL,
          timeoutMs: e.AI_TIMEOUT_MS,
        }
      : null
  );
  if (e.REMBG_URL && !/^https?:\/\/[^\s/]/i.test(e.REMBG_URL)) {
    throw new Error('Invalid configuration: REMBG_URL');
  }
  const removeBackground = resolveFeature(
    'REMBG',
    e.REMBG_ENABLED,
    'REMBG_URL',
    e.REMBG_URL ? { url: e.REMBG_URL.replace(/\/+$/, ''), timeoutMs: e.REMBG_TIMEOUT_MS } : null
  );
  return {
    databaseUrl: e.DATABASE_URL,
    host: e.HOST,
    port: e.PORT,
    dataDir: e.DATA_DIR.replace(/\/+$/, ''),
    uploadDir: `${e.DATA_DIR.replace(/\/+$/, '')}/uploads`,
    staticDir: e.STATIC_DIR,
    uploadMaxBytes: e.UPLOAD_MAX_BYTES,
    thumbnailMaxBytes: e.THUMBNAIL_MAX_BYTES,
    documentMaxBytes: e.DOCUMENT_MAX_BYTES,
    fontMaxBytes: e.FONT_MAX_BYTES,
    cookieSecure: e.COOKIE_SECURE,
    allowRegistration: e.ALLOW_REGISTRATION,
    allowInsecureCookie: !e.COOKIE_SECURE && !loopback,
    trustProxy: e.TRUST_PROXY,
    setupToken: e.SETUP_TOKEN ?? null,
    ai,
    features: { removeBackground },
  };
}
